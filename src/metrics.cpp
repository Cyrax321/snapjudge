Metrics compute_metrics(const std::vector<MetricPoint>& points) {
  Metrics m;
  m.n = (int)points.size();
  if (!m.n) return m;

  double brier = 0, soft = 0, tv = 0, nll = 0;
  std::vector<double> conf, corr;
  std::vector<double> expq, expt;  // score rows only
  int score_n = 0;
  double mae_sum = 0;

  for (const auto& p : points) {
    double b = 0, s = 0, tvd = 0, ce = 0;
    for (size_t j = 0; j < p.q.size(); ++j) {
      double d = p.q[j] - p.t[j];
      b += d * d;
      s += p.q[j] * p.t[j];
      tvd += std::fabs(d);
      ce += p.t[j] * std::log(std::max(p.q[j], 1e-12));
    }
    brier += b;
    soft += s;
    tv += tvd / 2;
    nll -= ce;
    conf.push_back(p.conf);
    corr.push_back(p.correct);
    if (p.qtype == 1) {
      double eq = 0, et = 0;
      for (size_t j = 0; j < p.q.size(); ++j) { eq += j * p.q[j]; et += j * p.t[j]; }
      mae_sum += std::fabs(eq - et);
      expq.push_back(eq);
      expt.push_back(et);
      ++score_n;
    }
  }
  m.brier = brier / m.n;
  m.soft = soft / m.n;
  m.tv = tv / m.n;
  m.nll = nll / m.n;
  m.ece = ece_score(conf, corr);
  m.accuracy = std::accumulate(corr.begin(), corr.end(), 0.0) / m.n;

  // MCE: max |bin_acc - bin_conf| over 15 bins
  {
    const int B = 15;
    double bc[15] = {0}, bn[15] = {0}, bcx[15] = {0};
    for (size_t i = 0; i < conf.size(); ++i) {
      int bb = std::min(B - 1, (int)(conf[i] * B));
      bc[bb] += corr[i];
      bcx[bb] += conf[i];
      bn[bb] += 1;
    }
    double mmax = 0;
    for (int b = 0; b < B; ++b)
      if (bn[b]) mmax = std::max(mmax, std::fabs(bc[b] / bn[b] - bcx[b] / bn[b]));
    m.mce = mmax;
  }
  m.auroc_conf = auroc(conf, corr);
  if (score_n) {
    m.score_mae = mae_sum / score_n;
    m.spearman = spearman(expq, expt);
  }
  return m;
}

std::map<std::string, std::pair<int, int>> accuracy_by_type(
    const std::vector<MetricPoint>& points) {
  std::map<std::string, std::pair<int, int>> out;
  const char* names[3] = {"choice", "score", "noul"};
  for (const auto& p : points) {
    auto& e = out[names[p.qtype]];
    e.first += p.correct >= 0.5 ? 1 : 0;
    ++e.second;
  }
  return out;
}

std::string metrics_latex(const Metrics& m, const std::string& ckpt_name) {
  std::ostringstream s;
  s.setf(std::ios::fixed);
  s.precision(4);
  s << "% snapjudge eval table — generated by snapjudge-plots\n"
       "\\begin{tabular}{lc}\n\\toprule\n"
       "\\multicolumn{2}{c}{" << ckpt_name << "} \\\\\n\\midrule\n";
  s << "Accuracy $\\uparrow$ & " << m.accuracy << " \\\\\n"
       "Soft score (q$\\cdot$t) $\\uparrow$ & " << m.soft << " \\\\\n"
       "TV distance $\\downarrow$ & " << m.tv << " \\\\\n"
       "NLL $\\downarrow$ & " << m.nll << " \\\\\n"
       "Brier $\\downarrow$ & " << m.brier << " \\\\\n"
       "ECE $\\downarrow$ & " << m.ece << " \\\\\n"
       "MCE $\\downarrow$ & " << m.mce << " \\\\\n"
       "AUROC (confidence $\\to$ correctness) $\\uparrow$ & " << m.auroc_conf << " \\\\\n";
  if (!std::isnan(m.score_mae)) s << "Score MAE $\\downarrow$ & " << m.score_mae << " \\\\\n";
  if (!std::isnan(m.spearman)) s << "Score Spearman $\\uparrow$ & " << m.spearman << " \\\\\n";
  s << "\\bottomrule\n\\end{tabular}\n";
  return s.str();
}

