// Mann-Whitney AUROC: P(conf_positive > conf_negative) with tie handling.
double auroc(const std::vector<double>& conf, const std::vector<double>& correct) {
  std::vector<std::pair<double, double>> pairs;
  for (size_t i = 0; i < conf.size(); ++i) pairs.emplace_back(conf[i], correct[i]);
  std::sort(pairs.begin(), pairs.end());
  size_t n_pos = 0;
  for (auto& p : pairs) if (p.second >= 0.5) ++n_pos;
  size_t n = pairs.size(), n_neg = n - n_pos;
  if (!n_pos || !n_neg) return NAN;
  // rank-sum with average ranks for ties
  double rsum = 0;
  size_t i = 0;
  while (i < n) {
    size_t j = i;
    while (j < n && pairs[j].first == pairs[i].first) ++j;
    double avg_rank = (i + j + 1) / 2.0;  // 1-based
    for (size_t k = i; k < j; ++k) if (pairs[k].second >= 0.5) rsum += avg_rank;
    i = j;
  }
  return (rsum - n_pos * (n_pos + 1) / 2.0) / (n_pos * (double)n_neg);
}

// Spearman rank correlation of two vectors.
double spearman(std::vector<double> a, std::vector<double> b) {
  size_t n = a.size();
  if (n < 2) return NAN;
  auto rankify = [](std::vector<double> v) {
    std::vector<size_t> ix(v.size());
    std::iota(ix.begin(), ix.end(), 0);
    std::sort(ix.begin(), ix.end(), [&](size_t p, size_t q) { return v[p] < v[q]; });
    std::vector<double> r(v.size());
    size_t i = 0;
    while (i < ix.size()) {
      size_t j = i;
      while (j < ix.size() && v[ix[j]] == v[ix[i]]) ++j;
      double avg = (i + j - 1) / 2.0 + 1;
      for (size_t k = i; k < j; ++k) r[ix[k]] = avg;
      i = j;
    }
    return r;
  };
  auto ra = rankify(std::move(a)), rb = rankify(std::move(b));
  double ma = std::accumulate(ra.begin(), ra.end(), 0.0) / n;
  double mb = std::accumulate(rb.begin(), rb.end(), 0.0) / n;
  double num = 0, da = 0, db = 0;
  for (size_t i = 0; i < n; ++i) {
    num += (ra[i] - ma) * (rb[i] - mb);
    da += (ra[i] - ma) * (ra[i] - ma);
    db += (rb[i] - mb) * (rb[i] - mb);
  }
  if (da == 0 || db == 0) return NAN;
  return num / std::sqrt(da * db);
}

